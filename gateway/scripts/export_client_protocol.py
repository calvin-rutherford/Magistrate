if __name__ == "__main__":
    from cryptography.fernet import Fernet

    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--write-types', action='store_true', help='Regenerate the foundation client types')
    group.add_argument('--check-types', action='store_true', help='Fail if generated foundation types drift')
    args = parser.parse_args()

    # Isolate all deployment configuration BEFORE validator imports. db.py now
    # defers initialization, but future validator imports must remain unable to
    # access a deployment's DB/state or provider/runtime credentials.
    with tempfile.TemporaryDirectory(prefix="magistrate-schema-") as temporary:
        for name in list(os.environ):
            if name.startswith(("MAGISTRATE_", "OPENAI_", "ANTHROPIC_", "GOOGLE_", "GITHUB_", "STRIPE_")) or name == "FM_HOME":
                del os.environ[name]
        os.environ.update({
            "MAGISTRATE_ENV": "test",
            "MAGISTRATE_DB_PATH": str(Path(temporary) / "schema.sqlite3"),
            "MAGISTRATE_SECRET_KEY": Fernet.generate_key().decode("ascii"),
        })
        target = Path(__file__).resolve().parents[2] / 'frontend/src/protocol/ObjectiveStateProtocol.ts'
        if args.write_types:
            target.write_text(objective_protocol_typescript())
        elif args.check_types:
            if not target.exists() or target.read_text() != objective_protocol_typescript():
                parser.exit(1, 'Foundation protocol drift: run --write-types and review the generated diff.\n')
        else:
            print(json.dumps(client_protocol(), ensure_ascii=False, indent=2, sort_keys=True))
