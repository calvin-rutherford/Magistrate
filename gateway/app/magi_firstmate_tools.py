class FirstmateSubmitObjectiveContract(BaseModel):
    """Strict arguments generated by the model for one actionable objective."""

    model_config = ConfigDict(extra="forbid", strict=True)

    objective: str = Field(min_length=1, max_length=MAX_OBJECTIVE_CHARS)
    project: str = Field(min_length=1, max_length=MAX_PROJECT_CHARS, pattern=_SAFE_PROJECT.pattern)
    constraints: list[str] = Field(min_length=0, max_length=MAX_OBJECTIVE_ITEMS)
    acceptance_criteria: list[str] = Field(min_length=1, max_length=MAX_OBJECTIVE_ITEMS)
    context_refs: list[str] = Field(min_length=0, max_length=MAX_CONTEXT_REFS)

    @field_validator("objective")
    @classmethod
    def validate_objective(cls, value: str) -> str:
        return _bounded_contract_text(value, maximum=MAX_OBJECTIVE_CHARS)

    @field_validator("constraints", "acceptance_criteria")
    @classmethod
    def validate_items(cls, values: list[str]) -> list[str]:
        checked = [
            _bounded_contract_text(value, maximum=MAX_OBJECTIVE_ITEM_CHARS)
            for value in values
        ]
        if len(set(checked)) != len(checked):
            raise ValueError("Objective list entries must be unique.")
        return checked

    @field_validator("context_refs")
    @classmethod
    def validate_context_refs(cls, values: list[str]) -> list[str]:
        if any(not isinstance(value, str) or not _SAFE_CONTEXT_REF.fullmatch(value) for value in values):
            raise ValueError("Objective context references must be bounded opaque identifiers.")
        if len(set(values)) != len(values):
            raise ValueError("Objective context references must be unique.")
        return values

    @model_validator(mode="after")
    def validate_aggregate_bounds(self) -> "FirstmateSubmitObjectiveContract":
        aggregate = (
            len(self.objective) + len(self.project)
            + sum(map(len, self.constraints))
            + sum(map(len, self.acceptance_criteria))
            + sum(map(len, self.context_refs))
        )
        if aggregate > MAX_OBJECTIVE_AGGREGATE_CHARS:
            raise ValueError("Objective arguments exceed the aggregate text bound.")
        encoded = _canonical_json(self.model_dump(mode="json")).encode("utf-8", errors="strict")
        if len(encoded) > MAGI_MAX_TOOL_ARGUMENT_BYTES:
            raise ValueError("Objective arguments exceed the encoded contract bound.")
        return self


def _bounded_contract_text(value: Any, *, maximum: int) -> str:
    if (
        not isinstance(value, str)
        or not value or value != value.strip()
        or len(value) > maximum
        or magi_text_has_unsafe_controls(value)
    ):
        raise ValueError("Objective text must be non-blank, bounded, and control-free.")
    try:
        value.encode("utf-8", errors="strict")
    except UnicodeEncodeError as exc:
        raise ValueError("Objective text must contain valid Unicode scalar values.") from exc
    return value


def _canonical_json(value: Any) -> str:
    return json.dumps(
        value, ensure_ascii=False, separators=(",", ":"), sort_keys=True, allow_nan=False,
    )


def _strict_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Objective arguments contain duplicate JSON keys.")
        result[key] = value
    return result


def _reject_json_constant(_: str) -> None:
    raise ValueError("Objective arguments contain a non-finite number.")


def parse_submit_objective_arguments(arguments_json: str) -> FirstmateSubmitObjectiveContract:
    """Decode raw provider arguments without accepting aliases or duplicate keys."""
    if not isinstance(arguments_json, str) or not arguments_json.strip():
        raise MagiToolError("objective_arguments_invalid", retryable=False)
    try:
        encoded = arguments_json.encode("utf-8", errors="strict")
    except UnicodeEncodeError as exc:
        raise MagiToolError("objective_arguments_invalid", retryable=False) from exc
    if len(encoded) > MAGI_MAX_TOOL_ARGUMENT_BYTES or magi_text_has_unsafe_controls(arguments_json):
        raise MagiToolError("objective_arguments_invalid", retryable=False)
    try:
        value = json.loads(
            arguments_json,
            object_pairs_hook=_strict_object,
            parse_constant=_reject_json_constant,
        )
        if not isinstance(value, dict):
            raise ValueError("Objective arguments must be an object.")
        return FirstmateSubmitObjectiveContract.model_validate(value)
    except (ValueError, TypeError, ValidationError, json.JSONDecodeError, RecursionError) as exc:
        raise MagiToolError("objective_arguments_invalid", retryable=False) from exc


